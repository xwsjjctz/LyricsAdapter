describe('decryptQrc', () => {
  it('decrypts a real QQ Music QRC payload into the LyricContent XML', () => {
    const decoded = decryptQrc(REAL_QRC_HEX);

    // Decrypts to the QRC XML envelope the renderer's parseQrc expects.
    expect(decoded).toContain('<?xml');
    expect(decoded).toContain('<QrcInfos>');
    expect(decoded).toContain('LyricContent=');

    // Per-word timing lines are present: `[startTime,duration]word(t,d)...`.
    expect(decoded).toMatch(/\[\d+,\d+\]/);
    expect(decoded).toMatch(/\(\d+,\d+\)/);
  });

  it('recovers the song title and word-level timings for the fixture track', () => {
    const decoded = decryptQrc(REAL_QRC_HEX);
    // 大鱼 (周深) — the fixture track. Confirms the full pipeline is correct,
    // not just that *some* XML came out.
    expect(decoded).toContain('大鱼');
    expect(decoded).toContain('周深');
  });

  it('throws on empty input', () => {
    expect(() => decryptQrc('')).toThrow(/16-char DES block/);
  });

  it('throws when the payload length is not a 16-char block multiple', () => {
    expect(() => decryptQrc('A1B2C3')).toThrow(/16-char DES block/);
  });

  it('throws on non-hex input that passes the length gate', () => {
    // 16 chars long so it clears the length check, but 'Z' is not a hex digit.
    expect(() => decryptQrc('ZZZZZZZZZZZZZZZZ')).toThrow();
  });
});
